#!/usr/bin/env node
/* tools-close-port-verify.js - prove the SERVER port computes what the local closer does.
 *
 *   node tools-close-port-verify.js
 *   node tools-close-port-verify.js --repo <path to coldufantasy-login>
 *
 * lib/close.js in the coldufantasy-login repo is a PORT of tools/close-stage.js. A port
 * is a second implementation, and a second implementation of scoring arithmetic is
 * exactly the FP_SCALE mistake waiting to happen: the two agree on the day they are
 * written and diverge quietly afterwards, and the one that drifts is the one nobody
 * watches, which here is the server.
 *
 * So the port is checked against RESULTS THAT ARE ALREADY STORED. Stage 17 was closed by
 * the local tool and written to Firestore on 2026-09-09; every number below came from
 * that close. If the port cannot reproduce them from the official feed, it is wrong.
 *
 * This talks to the live official feed and nothing else. It writes nothing, and it does
 * not need the API deployed or a key.
 */
'use strict';

const path = require('path');
const fs = require('fs');

const DEFAULT_API_REPO = path.resolve(__dirname, '..', 'coldufantasy-login');
function apiRepo() {
  const i = process.argv.indexOf('--repo');
  return i >= 0 ? process.argv[i + 1] : DEFAULT_API_REPO;
}

/* The stage 17 close, as actually stored. Not recomputed here on purpose: a fixture that
   is regenerated by the thing it tests proves nothing. */
const STAGE17 = {
  win: 'M. Brennan',
  combatif: 'E. Paleni',
  days: { AA: 23, JB: 136, JJ: 24, JP: 21 },
  fantasy: { AA: 40, JB: 40, JJ: 58, JP: 56 },
  rank: { AA: 9, JB: 11, JJ: 8, JP: 8 },
  kasseiTop: 'J. Meeus', kasseiF: 2, kasseiCorrect: ['AA', 'JJ', 'JP'],
  breakaway: false,
  classified: 149
};

/* Allen's ground truth, corrected 2026-09-09: stage 13 IS a fuga, because van Aert
   started the move and won from it. A rider who starts or joins the day's move and wins
   from it is a fuga regardless of whether he is a GC contender. */
const FUGAS = { 7: true, 12: true, 13: true, 15: true };

let fails = 0, ran = 0;
function check(label, ok, detail) {
  ran++;
  if (!ok) fails++;
  console.log('  [' + (ok ? 'PASS' : 'FAIL') + '] ' + String(label).padEnd(52) +
    (detail == null ? '' : detail));
}

async function main() {
  const repo = apiRepo();
  const closePath = path.join(repo, 'lib', 'close.js');
  if (!fs.existsSync(closePath)) {
    console.log('[SKIP] the coldufantasy-login clone is not at ' + repo);
    console.log('       Nothing was compared. This is NOT a pass.');
    process.exit(0);
  }

  const C = await import('file:///' + closePath.replace(/\\/g, '/'));
  const race = C.RACES.vuelta;

  /* the startlist, read the way the local closer reads it */
  const src = fs.readFileSync(path.join(__dirname, 'vuelta.src.html'), 'utf8');
  const rl = src.split('\n').find(l => l.startsWith('const RIDERS = ['));
  const riders = JSON.parse(rl.slice(rl.indexOf('['), rl.lastIndexOf(']') + 1));
  const bi = src.indexOf('const BELGIAN_RIDERS=[');
  const national = Array.from(src.slice(bi, src.indexOf('];', bi))
    .matchAll(/\{r:"([^"]+)"/g)).map(m => m[1]);
  const nameByBib = {}, bibByName = {}, teamByBib = {};
  riders.forEach(r => { nameByBib[r.b] = r.r; bibByName[r.r] = r.b; teamByBib[r.b] = r.t; });
  const tables = { riders, national, nameByBib, bibByName, teamByBib };

  /* the stage 17 draft, from the pool, so picks and kassei are the real ones */
  const KEY = process.env.CDF_KEY;
  if (!KEY) { console.error('CDF_KEY is not set.'); process.exit(2); }
  const psr = await fetch('https://api.coldufantasy.com/api/pool-state?pool=vuelta-2026&stage=17',
    { headers: { 'x-cdf-key': KEY } });
  const ps = await psr.json();
  const draft = ps.draft;

  console.log('STAGE 17, recomputed by the SERVER port and compared with what is stored\n');

  const res = await C.officialResult(race, 17);
  check('classification size', res.classified.length === STAGE17.classified,
    res.classified.length + ' vs ' + STAGE17.classified);

  const gates = C.runGates(res, 149, tables, draft);
  check('every gate passes', gates.every(g => g.ok),
    gates.filter(g => !g.ok).map(g => g.label).join('; ') || gates.length + ' gates');

  const scored = C.scoreStage(res, draft, tables);
  check('winner', (nameByBib[res.classified[0].bib] === STAGE17.win), nameByBib[res.classified[0].bib]);
  check('Placement per seat', JSON.stringify(scored.days) === JSON.stringify(STAGE17.days),
    JSON.stringify(scored.days));
  check('Fantasy Points per seat', JSON.stringify(scored.fantasy) === JSON.stringify(STAGE17.fantasy),
    JSON.stringify(scored.fantasy));
  check('Rank per seat', JSON.stringify(scored.rank) === JSON.stringify(STAGE17.rank),
    JSON.stringify(scored.rank));
  const rankTotal = Object.keys(scored.rank).reduce((a, k) => a + scored.rank[k], 0);
  check('rank total is 36', rankTotal === 36, String(rankTotal));

  const nat = C.nationalityGame(draft, tables, scored);
  check('Kasseistampers top', nat.top === STAGE17.kasseiTop && nat.f === STAGE17.kasseiF,
    nat.top + ' ' + nat.f);
  check('Kasseistampers shared three ways',
    JSON.stringify(nat.correct.slice().sort()) === JSON.stringify(STAGE17.kasseiCorrect.slice().sort()),
    JSON.stringify(nat.correct));
  check('a seat off target is reported, not dropped',
    nat.detail.length === 4 && nat.detail.some(d => d.seat === 'JB' && d.onTarget === false),
    nat.detail.map(d => d.seat + (d.onTarget ? '+' : '-')).join(' '));

  const cg = C.combatifGate({ stage: 17, bind: res.iceBind, bindStage: res.iceStage,
    proposed: null, prevCombatif: 'K. Vermaerke', riders });
  check('combatif through the gate', cg.ok && cg.value === STAGE17.combatif,
    cg.ok ? cg.value + ' (bib ' + cg.bib + ')' : cg.why);

  check('rotation advances one seat',
    JSON.stringify(C.rotate(['JJ', 'JP', 'JB', 'AA'])) === JSON.stringify(['JP', 'JB', 'AA', 'JJ']));
  let threw = false;
  try { C.rotate(['AA']); } catch (e) { threw = true; }
  check('rotation refuses a one-seat order', threw);

  /* ---- the breakaway rule, over every scored stage ---- */
  console.log('\nBREAKAWAY RULE over every scored stage\n');
  const scoredStages = ps.scoredStages;
  let right = 0, wrong = [];
  let prevGCByBib = null;
  const rows = [];
  for (const n of scoredStages) {
    const st = (ps.stages || []).find(x => x.n === n) || {};
    let r;
    try { r = await C.officialResult(race, n); } catch (e) { continue; }
    const j = C.judgeBreakaway(r, prevGCByBib, st.type);
    const truth = Boolean(FUGAS[n]);
    if (j.breakaway === truth) right++; else wrong.push(n);
    rows.push({ n, type: st.type, pred: j.breakaway, truth, stored: st.breakaway,
      confident: j.confident });
    prevGCByBib = {};
    (r.gc || []).forEach(x => { if (Number(x.position) > 0) prevGCByBib[x.bib] = Number(x.position); });
  }
  rows.forEach(r => console.log('   stage ' + String(r.n).padStart(2) + '  ' +
    String(r.type || '').padEnd(20) + ' predicted ' + String(r.pred).padEnd(5) +
    ' truth ' + String(r.truth).padEnd(5) + ' stored ' + String(r.stored).padEnd(5) +
    (r.confident ? '' : '  UNCERTAIN')));
  check('breakaway rule matches the ground truth', wrong.length <= 1,
    right + '/' + rows.length + (wrong.length ? ', misses ' + JSON.stringify(wrong) : ''));
  check('no false negatives, a real fuga is never called a bunch finish',
    !rows.some(r => r.truth && !r.pred),
    rows.filter(r => r.truth && !r.pred).map(r => r.n).join(',') || 'none');
  check('every confident call is correct',
    !rows.some(r => r.confident && r.pred !== r.truth),
    rows.filter(r => r.confident && r.pred !== r.truth).map(r => r.n).join(',') || 'none');
  check('breakThru is never auto-decided',
    rows.filter(r => r.pred).length > 0);

  console.log('\n' + (ran - fails) + '/' + ran + ' checks passed');
  process.exit(fails ? 1 : 0);
}

main().catch(e => { console.error('\nFAILED: ' + e.message); process.exit(1); });
